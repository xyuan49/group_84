import { render, screen } from '@testing-library/react'
import { describe, it, expect } from 'vitest'
import DataNotice from './DataNotice'
import SourceNote from './SourceNote'
import GlucoseChart from './GlucoseChart'
import InsulinChart from './InsulinChart'
import HbA1cChart from './HbA1cChart'
import { countBySource, sourceLabel } from '../dataSources'

const glucose = [
  { value_mg_dl: 140, measured_at: '2026-10-31T08:00:00', source: 'cgm' },
  { value_mg_dl: 150, measured_at: '2026-10-31T08:15:00', source: 'cgm' },
  { value_mg_dl: 132, measured_at: '2026-10-31T09:00:00', source: 'user' },
]

describe('data source labels', () => {
  it('marks paired research datasets', () => {
    expect(sourceLabel('cgm')).toBe('Shanghai T2DM CGM dataset (paired for demonstration)')
    expect(sourceLabel('uci')).toBe('UCI Diabetes dataset (paired for demonstration)')
    expect(sourceLabel('fhir')).toBe('Synthetic health record (Synthea, FHIR)')
    expect(sourceLabel('user')).toBe('Patient entries')
  })

  it('counts records by source in order of appearance', () => {
    expect(countBySource(glucose)).toEqual([
      { source: 'cgm', count: 2 },
      { source: 'user', count: 1 },
    ])
  })
})

describe('DataNotice', () => {
  it('says the patients are synthetic and the datasets are paired', () => {
    render(<DataNotice />)

    const notice = screen.getByRole('complementary', { name: 'About this data' })
    expect(notice).toHaveTextContent('Patients are synthetic records generated by Synthea')
    expect(notice).toHaveTextContent('paired with these synthetic patients for demonstration')
    expect(notice).toHaveTextContent('not real observations of these patients')
  })
})

describe('SourceNote', () => {
  it('lists each source with its count', () => {
    render(<SourceNote records={glucose} />)

    expect(screen.getByText(
      'Sources: Shanghai T2DM CGM dataset (paired for demonstration), 2 readings · Patient entries, 1 reading'
    )).toBeInTheDocument()
  })

  it('renders nothing without records', () => {
    const { container } = render(<SourceNote records={[]} />)
    expect(container).toBeEmptyDOMElement()
  })
})

describe('charts show their sources', () => {
  it('glucose chart', () => {
    render(<GlucoseChart readings={glucose} />)
    expect(screen.getByText(/^Sources: Shanghai T2DM CGM dataset \(paired for demonstration\), 2 readings/))
      .toBeInTheDocument()
  })

  it('insulin chart', () => {
    const doses = [{ units: 8, insulin_type: 'rapid', administered_at: '2026-10-31T07:30:00', source: 'uci' }]
    render(<InsulinChart readings={doses} />)
    expect(screen.getByText('Sources: UCI Diabetes dataset (paired for demonstration), 1 dose'))
      .toBeInTheDocument()
  })

  it('HbA1c chart', () => {
    render(<HbA1cChart readings={[]} />)
    expect(screen.getByText('Source: Synthetic health record (Synthea, FHIR)')).toBeInTheDocument()
  })
})
